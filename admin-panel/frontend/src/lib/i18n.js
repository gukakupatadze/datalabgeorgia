function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : `{${k}}`));
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    if (typeof window === "undefined") return "ka";
    return localStorage.getItem(STORAGE_KEY) || "ka";
  });

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
      document.documentElement.lang = lang;
    } catch (e) {
      /* ignore */
    }
  }, [lang]);

  const setLang = useCallback((l) => setLangState(l), []);

  const t = useCallback(
    (key, vars) => {
      const table = translations[lang] || translations.ka;
      const value = table[key] ?? translations.en[key] ?? key;
      return interpolate(value, vars);
    },
    [lang]
  );

  const dateLocale = lang === "ka" ? kaLocale : undefined;

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dateLocale }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
